"""Field incident reports API routes."""
from __future__ import annotations

from typing import List, Optional
from fastapi import APIRouter, Depends, File, Form, HTTPException, Query, UploadFile, status
from fastapi.responses import FileResponse

from src.api.dependencies import get_current_user, require_authenticated, require_patrol
from src.api.schemas.auth import UserProfile
from src.api.schemas.reports import (
    PublicReportItem,
    ReportAssignRequest,
    ReportListResponse,
    ReportResponse,
    ReportStatusUpdateRequest,
    ReportSummaryStats,
)
from src.services.report_service import report_service

router = APIRouter(prefix="/v1/reports", tags=["Field Reports"])


@router.post("", response_model=ReportResponse, status_code=status.HTTP_201_CREATED)
async def create_report(
    client_uuid: str = Form(..., description="Idempotency key generated by client (UUIDv4)"),
    category: str = Form(..., description="Report category"),
    latitude: float = Form(..., description="WGS84 latitude"),
    longitude: float = Form(..., description="WGS84 longitude"),
    description: Optional[str] = Form(None, description="Optional incident description (max 1000 chars)"),
    client_created_at: Optional[str] = Form(None, description="ISO timestamp of client capture"),
    photo: Optional[UploadFile] = File(None, description="Optional JPEG/PNG/WebP photo evidence"),
    current_user: UserProfile = Depends(require_authenticated),
) -> ReportResponse:
    """Submits a new field report. Idempotent on client_uuid.
    
    Accessible to authenticated users ('user', 'patrol', 'admin'). Guests cannot submit reports.
    """
    if description and len(description) > 1000:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail="Description must not exceed 1000 characters.",
        )

    return report_service.create_report(
        client_uuid=client_uuid,
        category=category,
        description=description,
        latitude=latitude,
        longitude=longitude,
        client_created_at=client_created_at,
        photo=photo,
        reporter=current_user,
    )


@router.get("/mine", response_model=List[ReportResponse])
def get_my_reports(
    current_user: UserProfile = Depends(require_authenticated),
) -> List[ReportResponse]:
    """Retrieves all reports submitted by the authenticated reporter."""
    return report_service.get_user_reports(current_user.id)


@router.get("/public", response_model=List[PublicReportItem])
def get_public_reports() -> List[PublicReportItem]:
    """Returns verified and assigned reports for map overlay.
    
    Accessible to all users and guests. Reporter identities are omitted for privacy.
    Unverified and rejected reports are never returned publicly.
    """
    return report_service.get_public_reports()


@router.get("/summary", response_model=ReportSummaryStats)
def get_report_summary(
    _: UserProfile = Depends(require_patrol),
) -> ReportSummaryStats:
    """Returns report breakdown counts across statuses for Patrol Operations Dashboard."""
    return report_service.get_summary_stats()


@router.get("", response_model=ReportListResponse)
def list_reports(
    status: Optional[str] = Query(None, description="Filter by status: submitted, verified, assigned, resolved, rejected"),
    category: Optional[str] = Query(None, description="Filter by category"),
    segment_id: Optional[str] = Query(None, description="Filter by corridor segment ID"),
    assignee_id: Optional[int] = Query(None, description="Filter by patrol officer ID"),
    limit: int = Query(50, ge=1, le=100),
    offset: int = Query(0, ge=0),
    _: UserProfile = Depends(require_patrol),
) -> ReportListResponse:
    """Patrol queue endpoint with filtering, search, and pagination. Restricted to patrol/admin."""
    return report_service.get_patrol_reports(
        status=status,
        category=category,
        segment_id=segment_id,
        assignee_id=assignee_id,
        limit=limit,
        offset=offset,
    )


@router.get("/{report_id}", response_model=ReportResponse)
def get_report(
    report_id: str,
    current_user: UserProfile = Depends(get_current_user),
) -> ReportResponse:
    """Retrieves report details. Enforces object-level authorization (IDOR protection)."""
    return report_service.get_report_by_id(report_id, current_user)


@router.patch("/{report_id}/status", response_model=ReportResponse)
def update_status(
    report_id: str,
    req: ReportStatusUpdateRequest,
    current_user: UserProfile = Depends(require_patrol),
) -> ReportResponse:
    """Transitions report status with audit trail logging. Restricted to patrol/admin."""
    return report_service.update_report_status(
        report_id=report_id,
        new_status=req.status.value,
        note=req.note,
        actor=current_user,
    )


@router.patch("/{report_id}/assign", response_model=ReportResponse)
def assign_report(
    report_id: str,
    req: ReportAssignRequest,
    current_user: UserProfile = Depends(require_patrol),
) -> ReportResponse:
    """Assigns report to a patrol officer. Restricted to patrol/admin."""
    return report_service.assign_report(
        report_id=report_id,
        assignee_id=req.assigned_to,
        note=req.note,
        actor=current_user,
    )


@router.get("/{report_id}/photo")
def get_photo(
    report_id: str,
    current_user: UserProfile = Depends(get_current_user),
) -> FileResponse:
    """Serves incident photo evidence securely after validating caller authorization."""
    path = report_service.get_photo_path(report_id, current_user)
    media_type = "image/jpeg" if path.suffix.lower() in (".jpg", ".jpeg") else (
        "image/png" if path.suffix.lower() == ".png" else "image/webp"
    )
    return FileResponse(path, media_type=media_type)
